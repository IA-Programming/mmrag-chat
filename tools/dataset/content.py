"""Static content of the fictional Saltmere Archipelago (dataset synth_v1).

Everything here is invented: islands, towns, people, organisations and numbers do not exist, so
nothing can be answered from a model's pretraining knowledge. The builder in `world.py` combines
these pools with a seeded RNG; this module holds data only.

Filler sentences deliberately contain no digits and no colour words, so that every number or
colour in the corpus belongs to a planted fact.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class V:
    """Value spec for a planted fact. kind: int | dec | money | year | person | pick | fixed | month | town | place."""

    kind: str
    lo: float = 0
    hi: float = 0
    unit: str = ""
    pool: str = ""


@dataclass(frozen=True)
class Template:
    key: str
    section: str  # pool key of the section the fact paragraph lives in
    phrasings: tuple[str, str]  # [0] base wording, [1] paraphrase (used by near-duplicate docs)
    question: str
    value: V
    followup: str = ""  # pronoun/ellipsis form used inside dialogues
    es: str = ""  # Spanish question (multilingual queries)
    ja: str = ""  # Japanese question (multilingual queries)


@dataclass(frozen=True)
class Entity:
    name: str
    island: str
    article: bool = True
    fixed: tuple[tuple[str, str, str], ...] = ()  # (key, text, keyword)


@dataclass(frozen=True)
class DocType:
    kind: str
    kind_noun: str  # "the lighthouse"
    subtitle: str
    headings: tuple[tuple[str, str], ...]  # (heading, pool key)
    templates: tuple[Template, ...]
    flavor: tuple[str, ...]
    entities: tuple[Entity, ...]
    dialogue: tuple[str, ...]  # template keys, in turn order


